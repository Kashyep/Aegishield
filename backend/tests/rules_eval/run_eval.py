"""MOD-07 rule retrieval evaluation (M5-D10). Run from backend/: python -m tests.rules_eval.run_eval"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.rules import rank_passages, rule_applicability, validate_rules  # noqa: E402
from conftest import ROOT, apply_patches, golden, load_fx  # noqa: E402

CASES = [c for c in json.loads((ROOT / "fixtures/validation/cases.json").read_text(encoding="utf-8"))["cases"]
         if c["case_id"].startswith("VC-RULE")]


def evaluate() -> dict:
    scenarios = [(g["query"]["query_id"], [], g["query"],
                  {"outcome": g["outcome"], "applicable_rule_ids": [a["rule_id"] for a in g["applicable"]],
                   "excluded": {e["rule_id"]: e["reason"] for e in g["excluded"]}})
                 for g in golden("rule_applicability.json")["results"]]
    scenarios += [(c["case_id"], c["patches"], c["input"]["query"], c["expected"]) for c in CASES]
    exact = reasons_ok = reasons_n = leakage = cites_ok = cites_n = 0
    unresolved_detected, rows = None, []
    for name, patches, q, exp in scenarios:
        fx = apply_patches(load_fx(), patches)
        rules = validate_rules(fx["trade_rules"])
        by_id = {r["rule_id"]: r for r in rules}
        r = rule_applicability(q, rules, fx["master_data"]["agreements"])
        got = [a["rule_id"] for a in r["applicable"]]
        exact += got == exp["applicable_rule_ids"]
        why = {e["rule_id"]: e["reason"] for e in r["excluded"]}
        for rid, reason in exp.get("excluded", {}).items():
            reasons_n += 1
            reasons_ok += why.get(rid) == reason
        leakage += sum(by_id[a]["status"] != "in_force" or why.get(a) == "superseded" for a in got)
        leakage += sum(any(a in by_id[o]["supersedes"] for o in got) for a in got)
        for a in r["applicable"]:
            cites_n += 1
            cites_ok += a["citation"]["source_id"] == by_id[a["rule_id"]]["source"]["source_id"]
        if name == "VC-RULE-03":
            unresolved_detected = r["outcome"] == "needs_review" and any(c["resolution"] == "unresolved" for c in r["conflicts"])
        top = rank_passages(q, r, rules, k=3)
        rows.append((name, r["outcome"], ", ".join(got) or "-", ", ".join(h["rule_id"] for h in top) or "-",
                     "yes" if r["outcome"] == exp["outcome"] else "NO"))
    n = len(scenarios)
    return {"cases": n, "rows": rows, "exactness": exact / n, "reason_accuracy": reasons_ok / reasons_n,
            "leakage": leakage, "unresolved_detected": unresolved_detected, "citation_integrity": cites_ok / cites_n}


def report(m: dict) -> str:
    rows = "\n".join(f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in m["rows"])
    return f"""# MOD-07 rule retrieval evaluation report

Generated by `python -m tests.rules_eval.run_eval` (from `backend/`). Synthetic rules only.
Selection is the deterministic metadata filter; BM25 ranks passages for display and is never used for selection.

| Metric | Result | Target |
|---|---|---|
| Applicable-set exactness | {m['exactness']:.0%} | 100% |
| Exclusion-reason accuracy | {m['reason_accuracy']:.0%} | 100% |
| Superseded/draft leakage | {m['leakage']} | 0 |
| Unresolved-conflict detection (VC-RULE-03) | {'yes' if m['unresolved_detected'] else 'NO'} | yes |
| Citation integrity | {m['citation_integrity']:.0%} | 100% |

## Cases ({m['cases']})
| Case | Outcome | Applicable | Top-3 passages (display only) | Outcome as expected |
|---|---|---|---|---|
{rows}
"""


if __name__ == "__main__":
    m = evaluate()
    (Path(__file__).resolve().parents[2] / "app/rules/EVAL.md").write_text(report(m), encoding="utf-8")
    print(report(m))
