"""MOD-05 graph retrieval evaluation harness (M4-D7). Run: python -m tests.graph_eval.run_eval  (from backend/)"""
from __future__ import annotations

import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.agents.dependency.check import check_dependency  # noqa: E402
from app.agents.dependency.explain import template_explanation, validate_explanation  # noqa: E402
from app.agents.dependency.graph import build_graph  # noqa: E402
from app.agents.dependency.linearize import linearize  # noqa: E402
from app.agents.sensing import assess_disruption  # noqa: E402
from conftest import ROOT, apply_patches, load_fx  # noqa: E402

CASES = json.loads((ROOT / "fixtures/validation/cases.json").read_text(encoding="utf-8"))["cases"]
# Cases whose data defect means "passed" would be a false pass.
RISKY_REASONS = {"INCOMPLETE_DEPENDENCY_DATA", "UNVERIFIED_PATH_TO_DISRUPTED_NODE", "TRAVERSAL_TRUNCATED",
                 "DISRUPTED_NODE_UNKNOWN"}


def _run(fx, supplier, part, max_depth=None, disrupted=None):
    g = build_graph(fx["supply_graph"], fx["master_data"])
    if disrupted is None:
        disrupted = assess_disruption(fx["disruptions"]["events"][0], fx)["disrupted_node_ids"]
    pol = fx["policies"]["dependency_policy"]
    q = {"supplier_id": supplier, "part_id": part, "disrupted_node_ids": disrupted,
         "max_depth": max_depth or pol["max_depth"]}
    t = time.perf_counter()
    r = check_dependency(q, g, fx["master_data"]["parts"], pol)
    return g, r, (time.perf_counter() - t) * 1000


def evaluate() -> dict:
    scenarios = [("DEMO-SUP-B", [], {"supplier_id": "SUP-B", "part_id": "PRT-PM750"},
                  {"outcome": "blocked", "disrupted_path_edge_ids": ["E-004", "E-005"]}),
                 ("DEMO-SUP-C", [], {"supplier_id": "SUP-C", "part_id": "PRT-PM750"}, {"outcome": "passed"})]
    for c in CASES:
        if c["case_id"].startswith("VC-DEP"):
            exp = dict(c["expected"])
            if c["case_id"] == "VC-DEP-04":  # patch only downgrades E-005 confidence; the same path must still be found
                exp["disrupted_path_edge_ids"] = ["E-004", "E-005"]
            scenarios.append((c["case_id"], c["patches"], c["input"], exp))
    # extra: unknown disruption
    scenarios.append(("UNKNOWN-DISRUPTION", [], {"supplier_id": "SUP-B", "part_id": "PRT-PM750", "_disrupted": []},
                      {"outcome": "needs_review"}))

    exp_paths = found_exp = reported = reported_ok = 0
    false_pass = determinism_ok = grounded = explained = 0
    lat, rows = [], []
    for name, patches, inp, exp in scenarios:
        fx = apply_patches(load_fx(), patches)
        kw = dict(max_depth=inp.get("max_depth"), disrupted=inp.get("_disrupted"))
        g, r, ms1 = _run(fx, inp["supplier_id"], inp["part_id"], **kw)
        _, r2, ms2 = _run(fx, inp["supplier_id"], inp["part_id"], **kw)
        lat += [ms1, ms2]
        determinism_ok += json.dumps(r, sort_keys=True) == json.dumps(r2, sort_keys=True)
        got = [tuple(p["edge_ids"]) for p in r["paths"] if p["kind"] == "shared_disrupted_dependency"]
        want = [tuple(exp["disrupted_path_edge_ids"])] if "disrupted_path_edge_ids" in exp else []
        exp_paths += len(want)
        found_exp += sum(w in got for w in want)
        reported += len(got)
        reported_ok += sum(x in want for x in got)
        if r["outcome"] == "passed" and (r["reason_code"] in RISKY_REASONS or not r["coverage"]["complete"] or r["truncated"]):
            false_pass += 1
        if name in ("VC-DEP-03", "VC-DEP-04", "VC-DEP-06", "UNKNOWN-DISRUPTION") and r["outcome"] == "passed":
            false_pass += 1
        ctx = linearize(r, g)
        expl = template_explanation(r, g, fx["master_data"]["parts"])
        explained += 1
        grounded += not validate_explanation(expl, ctx, r)
        rows.append((name, r["outcome"], r["reason_code"], exp.get("outcome", "-")))
        if "outcome" in exp and exp["outcome"] != r["outcome"]:
            false_pass += r["outcome"] == "passed"
    n = len(scenarios)
    return {"cases": n, "rows": rows,
            "recall": found_exp / exp_paths if exp_paths else 1.0,
            "precision": reported_ok / reported if reported else 1.0,
            "false_pass_cases": false_pass, "determinism": determinism_ok / n,
            "grounding": grounded / explained,
            "latency_ms_median": statistics.median(lat), "latency_ms_max": max(lat)}


def report(m: dict) -> str:
    rows = "\n".join(f"| {a} | {b} | {c} | {d} |" for a, b, c, d in m["rows"])
    return f"""# MOD-05 graph evaluation report

Generated by `python -m tests.graph_eval.run_eval` (from `backend/`). Synthetic data only.

| Metric | Result | Target |
|---|---|---|
| Disrupted-path recall | {m['recall']:.2f} | 1.0 |
| Path precision | {m['precision']:.2f} | 1.0 |
| False-pass cases | {m['false_pass_cases']} | 0 |
| Determinism (identical JSON, two runs) | {m['determinism']:.0%} | 100% |
| Explanation grounding (template) | {m['grounding']:.0%} | 100% |
| `check_dependency` latency, median / max over {2 * m['cases']} runs | {m['latency_ms_median']:.2f} ms / {m['latency_ms_max']:.2f} ms | <= 50 ms (re-measure on D8 on the demo laptop) |

Grounding is measured on the deterministic template; recorded-LLM grounding is measured once Member 5's gateway is wired.

## Cases ({m['cases']})
| Case | Outcome | Reason | Expected outcome |
|---|---|---|---|
{rows}
"""


if __name__ == "__main__":
    m = evaluate()
    out = Path(__file__).resolve().parents[2] / "app/agents/dependency/EVAL.md"
    out.write_text(report(m), encoding="utf-8")
    print(report(m))
